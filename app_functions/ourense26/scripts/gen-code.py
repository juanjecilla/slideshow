#!/usr/bin/env python3
# Regenerates deck/code.ts from the demo project so slides show the demo's real code.
# Usage: python3 -I scripts/gen-code.py   (DEMO_DIR to override the demo path). Review the diff, then npm run build && npm run verify.
import re, subprocess, sys, json
import os
D=os.path.expanduser(os.environ.get('DEMO_DIR','~/Projects/Demos/DevfestOurense26'))+'/'
# What the live demo / the slides use. Keep in sync with the demo repo docs/DEMO.md and scripts/capture-demo.sh.
DEMO_TRACK,DEMO_AFTER,DEMO_IDS,DEMO_QUERY='ai','15:00',['t15','t21'],'gema'
VERSION=re.search(r'^appfunctions = "([^"]+)"',open(D+'gradle/libs.versions.toml').read(),re.M).group(1)
def read(p, ref=None):
    if ref: return subprocess.check_output(['git','-C',D,'show',f'{ref}:{p}'],text=True).split('\n')
    return open(D+p).read().split('\n')
def dedent(lines,n): return [l[n:] if l.strip() else '' for l in lines]
def find(lines, pat, start=0):
    for i in range(start,len(lines)):
        if pat in lines[i]: return i
    raise SystemExit('not found: '+pat)
def func(lines, name):
    """KDoc start .. closing brace of the function named `name` (4-space class indent)."""
    i=find(lines,f'fun {name}(')
    k=i
    while not lines[k].strip().startswith('/**'): k-=1
    e=i
    while lines[e]!='    }': e+=1
    return k,e
SV='app/src/main/java/com/example/devfest/appfunctions/BaseAgendaAppFunctionService.kt'
sv=read(SV)
k,e=func(sv,'searchTalks')
FUNCTION=dedent(sv[k:e+1],4)
# signature-only version (KDoc + annotations + signature, body elided)
sig_end=find(sv,'): List<Talk> = withContext(Dispatchers.IO) {',k)
FUNCTION_SIG=dedent(sv[k:sig_end+1],4)
# "Bad" KDoc = the minimal first-pass KDoc the skill workflow starts from (tag cp-02b-implemented: 'Searches talks.' / 'Track.' /
# 'Start time.'), on today's real signature, so the only difference with KDOC_GOOD is the documentation.
sig_start=find(sv,'@AppFunctionDeclaration',k)
KDOC_BAD=['/**',' * Searches talks.',' *',' * @param track Track.',' * @param after Start time.',' * @param query Query.',' */']+dedent(sv[sig_start:sig_end+1],4)
ENTRY=sv[find(sv,'@RequiresApi(36)'):find(sv,'@Inject internal lateinit var getFavouritesUseCase')+1]+['','    // …','}']
ak,ae=func(sv,'addToFavorites')
body=dedent(sv[ak:ae+1],4)
i0=find(body,'if (talkIds.isEmpty())')
ERRORS=dedent(body[i0:-1],4)
INPUT_GUARD=ERRORS[:2]
ck,ce=func(sv,'clearFavorites')
CONFIRM=dedent(sv[ck:ce+1],4)
CONFIRM=CONFIRM[:CONFIRM.index('    clearFavouritesUseCase()')]+['    // …','}']
md=read('app/src/main/java/com/example/devfest/appfunctions/AgendaModels.kt')
SERIAL=md[find(md,'/** A session of'):md.index(')',find(md,'data class Talk('))+1]
STATE=md[find(md,'/** Result of'):]
while STATE and not STATE[-1].strip(): STATE.pop()
man=read('app/src/main/AndroidManifest.xml')
MANIFEST=dedent(man[find(man,'<service'):find(man,'android:resource="@xml/app_metadata" />')+1],8)
am=read('app/src/main/res/xml/app_metadata.xml')[1:]
while not am[-1].strip(): am.pop()
def ts(name,lines,doc=''):
    out=(f'/** {doc} */\n' if doc else '')+f'export const {name} = [\n'
    for l in lines: out+='  '+json.dumps(l,ensure_ascii=False)+',\n'
    return out+'];\n\n'
head='''/**
 * GENERATED by scripts/gen-code.py from ~/Projects/Demos/DevfestOurense26 (branch main);
 * snippets are the demo's real code, character for character, except lines marked with an ellipsis (…).
 * Library: androidx.appfunctions '''+VERSION+''' (see research.md B6).
 */

'''
o=head
o+=ts('GRADLE',['android {','    compileSdk = 37','','    defaultConfig {','        targetSdk = 36','    }','}','','ksp {','    arg("appfunctions:aggregateAppFunctions", "true")','}','','dependencies {','    implementation("androidx.appfunctions:appfunctions:'+VERSION+'")','    ksp("androidx.appfunctions:appfunctions-compiler:'+VERSION+'")','}'],'The demo uses a version catalog; coordinates written out as in the docs.')
o+=ts('FUNCTION',FUNCTION_SIG+['    // …','}']); o+=ts('FUNCTION_SIG',FUNCTION_SIG)
o+=ts('SERIALIZABLE',SERIAL); o+=ts('ENTRY_POINT',ENTRY); o+=ts('MANIFEST',MANIFEST)
o+=ts('ERRORS',ERRORS); o+=ts('INPUT_GUARD',INPUT_GUARD)
o+=ts('TYPES_BAD',['// the model has to guess','fun addToFavorites(talk: String)','// "the one about Compose?"'])
o+=ts('TYPES_GOOD',['// the model passes what it found','fun addToFavorites(talkIds: List<String>)','// ids come from searchTalks'])
o+=ts('IDEMPOTENT',[f'addToFavorites(["{DEMO_IDS[0]}"])  → favourites = [{DEMO_IDS[0]}]']*2)
o+=ts('CONFIRM',CONFIRM); o+=ts('STATE_RESULT',STATE)
o+=ts('KDOC_BAD',KDOC_BAD+['    // …','}']); o+=ts('KDOC_GOOD',FUNCTION_SIG+['    // …','}']); o+=ts('APP_METADATA',am)
o+=ts('DYNAMIC',['// Android 17 · API 37 · experimental in Jetpack','appFunctionManager.registerAppFunction(','    functionIdentifier,','    executor,','    appFunction,',')'])
o+='''export const PKG = 'com.example.devfest';
export const SVC = 'com.example.devfest.appfunctions.BaseAgendaAppFunctionService';

export const ADB_LIST = [
  '$ adb shell cmd app_function list-app-functions \\\\',
  `      | grep --after-context 10 ${PKG}`,
];

export const ADB_SEARCH = [
  `$ SVC=${SVC}`,
  '$ adb shell "cmd app_function execute-app-function \\\\',
  `      --package ${PKG} \\\\`,
  `      --function '$SVC#searchTalks' \\\\`,
  '      --parameters \\'{\\\\"track\\\\": \\\\"__TRACK__\\\\", \\\\"after\\\\": \\\\"__AFTER__\\\\"}\\'"',
];

export const ADB_ADD = [
  `$ SVC=${SVC}`,
  '$ adb shell "cmd app_function execute-app-function \\\\',
  `      --package ${PKG} \\\\`,
  `      --function '$SVC#addToFavorites' \\\\`,
  '      --parameters \\'{\\\\"talkIds\\\\": [__IDS__]}\\'"',
];

export const ADB_STOP = [`$ adb shell am force-stop ${PKG}`];

export const SKILLS_CMD = ['$ android skills add appfunctions'];
'''
o=o.replace('__TRACK__',DEMO_TRACK).replace('__AFTER__',DEMO_AFTER).replace('__IDS__',', '.join('\\\\"'+i+'\\\\"' for i in DEMO_IDS))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','deck','code.ts'),'w').write(o)
print('ok', len(FUNCTION), len(ERRORS), len(CONFIRM), len(MANIFEST))

# ---- demo captures → deck/captures.ts (+ copies in reference/demo-captures/) ----
import glob, shutil, textwrap
caps={}
refdir=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','reference','demo-captures')
shutil.rmtree(refdir,ignore_errors=True)
os.makedirs(refdir,exist_ok=True)
for f in sorted(glob.glob(D+'docs/captures/*.txt')):
    name=os.path.basename(f)[:-4]
    shutil.copy(f,os.path.join(refdir,os.path.basename(f)))
    lines=[]
    for l in open(f).read().rstrip('\n').split('\n'):
        l=l.rstrip()
        if len(l)>92:   # display only: wrap long error lines, continuation indented
            w=textwrap.wrap(l,92,subsequent_indent='  ',break_long_words=False)
            lines+=w
        else: lines.append(l)
    caps[name]=lines
c='/** GENERATED by scripts/gen-code.py from the demo project docs/captures (real adb output; long lines wrapped for display). */\n'
c+='export const CAPTURES: Record<string, string[]> = {\n'
for k,v in caps.items():
    c+='  '+json.dumps(k)+': [\n'+''.join('    '+json.dumps(x,ensure_ascii=False)+',\n' for x in v)+'  ],\n'
c+='};\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','deck','captures.ts'),'w').write(c)
print('captures',len(caps))
