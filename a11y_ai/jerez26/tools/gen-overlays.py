#!/usr/bin/env python3
"""Generate deck/overlays.ts: the boxes drawn over device screenshots, from the real UiAutomator dumps.

Every box is a node of a dump in reference/audit/ (bounds in screen pixels, 1080x2424), turned into fractions of the
screen so any screenshot size works. The navigation-bar, backdrop and synopsis boxes are annotations placed by hand (the tree audit
sees nothing there: that is the point of the beat) and are marked `hand: true`.
"""
import json, pathlib, re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
REF = ROOT / "reference/audit"
W, H = 1080, 2424


def nodes(path):
    return list(ET.parse(REF / path).getroot().iter("node"))


def bounds(n):
    m = re.match(r"\[(\d+),(\d+)\]\[(\d+),(\d+)\]", n.get("bounds", ""))
    return tuple(map(int, m.groups()))


def box(b, label, tone, hand=False, below=False):
    x0, y0, x1, y1 = b
    d = {"x": round(x0 / W, 4), "y": round(y0 / H, 4), "w": round((x1 - x0) / W, 4), "h": round((y1 - y0) / H, 4), "label": label, "tone": tone}
    if hand:
        d["hand"] = True
    if below:
        d["below"] = True
    return d


def label(n):
    return (n.get("content-desc") or n.get("text") or "").strip()


def has_label_below(n):
    return any(label(c) or has_label_below(c) for c in n)


def unlabeled(path, cls=None, size=None):
    out = []
    for n in nodes(path):
        if n.get("clickable") == "true" and not label(n) and not has_label_below(n) and (cls is None or n.get("class", "").endswith(cls)):
            x0, y0, x1, y1 = bounds(n)
            if size is None or (abs((x1 - x0) / 2.625 - size[0]) < 3 and abs((y1 - y0) / 2.625 - size[1]) < 3):
                out.append(bounds(n))
    return out


def clickable_with_text(path, text):
    best = None
    for n in nodes(path):
        if n.get("clickable") == "true" and text in label(n) + "".join(label(c) for c in n.iter("node")):
            b = bounds(n)
            if best is None or (b[2] - b[0]) * (b[3] - b[1]) < (best[2] - best[0]) * (best[3] - best[1]):
                best = b
    return best


def text_node(path, text, clickable=None):
    for n in nodes(path):
        if label(n) == text and (clickable is None or (n.get("clickable") == "true") == clickable):
            return bounds(n)


OV = {}
OV["searchBefore"] = [box(b, "unlabeled", "bad") for b in unlabeled("broken/search.xml", "EditText")]
OV["settingsBefore"] = [box(b, "unlabeled", "bad") for b in unlabeled("broken/settings.xml", "View", (52, 48))]
OV["settingsAfter"] = [box(clickable_with_text("main/settings.xml", "Notifications"), "one label", "ok")]
cb = unlabeled("main/detail2.xml", "CheckBox")
OV["detailBefore"] = [box(b, "unlabeled", "bad") for b in cb] + [box(clickable_with_text("main/detail2.xml", "Mark as watched"), "row: button", "info", below=True)]
OV["detailAfter"] = [box(clickable_with_text("fixed/detail.xml", "Mark as watched"), "one checkbox", "ok")]
OV["triageBefore"] = [
    box(text_node("main/triage.xml", "Matchbox the Movie"), "read, but hidden", "bad"),
    box(text_node("main/triage.xml", "Hope"), "read, but hidden", "bad"),
]
OV["postersBefore"] = [
    box(clickable_with_text("before-fix/posters.xml", "Spider-Man: Brand New Day"), "1 · button", "info"),
    box(text_node("before-fix/posters.xml", "Spider-Man: Brand New Day", clickable=False), "2 · text, again", "bad", below=True),
]
OV["navBefore"] = [box((0, 2185, 1080, 2340), "labels break mid-word", "bad", hand=True)]
OV["detailBackdrop"] = [box((0, 142, 1080, 775), "backdrop: no description", "info", hand=True)]
OV["synopsis"] = [box((42, 980, 1038, 1345), "68 words, one block", "info", hand=True)]
OV["navAfter"] = [box((0, 2185, 1080, 2340), "whole words", "ok", hand=True)]

(ROOT / "deck/overlays.ts").write_text(
    "// GENERATED by tools/gen-overlays.py from reference/audit/ (UiAutomator bounds). Do not edit.\n"
    "export interface Ov { x: number; y: number; w: number; h: number; label: string; tone: 'bad' | 'ok' | 'info'; hand?: boolean; below?: boolean }\n"
    "export const OV: Record<string, Ov[]> = " + json.dumps(OV, indent=2) + ";\n"
)
print({k: len(v) for k, v in OV.items()})
