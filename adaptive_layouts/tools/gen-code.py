#!/usr/bin/env python3
"""Generates deck/code.ts from the Muviss sources, so the code on stage is copied, never retyped.

Run:  python3 tools/gen-code.py [path/to/Muviss]
Each snippet is a list of (first, last) line ranges of one file, joined by a `// …` line when they are not
contiguous, and dedented. `sub` replaces a whole line by an explicit abbreviation (written with `…`) when the real
line is wider than the stage. Muviss refs in docs/research.md are pinned to the commit printed at the end.
"""
import json, subprocess, sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / 'Projects/CodingPit/Muviss')
OUT = Path(__file__).resolve().parent.parent / 'deck' / 'code.ts'

APP = 'app/shared/src/commonMain/kotlin/com/codingpit/muviss/MuvissApp.kt'
INS = 'core/designsystem/src/commonMain/kotlin/com/codingpit/muviss/core/designsystem/layout/ScreenInsets.kt'
ACT = 'app/androidApp/src/main/kotlin/com/codingpit/muviss/MainActivity.kt'
DET = 'feature/search/ui/src/commonMain/kotlin/com/codingpit/muviss/feature/search/ui/DetailScreen.kt'
PRO = 'feature/profile/ui/src/commonMain/kotlin/com/codingpit/muviss/feature/profile/ui/ProfileCharts.kt'
SEA = 'feature/search/ui/src/commonMain/kotlin/com/codingpit/muviss/feature/search/ui/SearchScreen.kt'
MAIN = 'app/desktopApp/src/main/kotlin/com/codingpit/muviss/Main.kt'
WIN = 'app/desktopApp/src/main/kotlin/com/codingpit/muviss/DesktopWindowState.kt'
TRI = 'feature/triage/ui/src/commonMain/kotlin/com/codingpit/muviss/feature/triage/ui/TriageScreen.kt'
MAN = 'app/androidApp/src/main/AndroidManifest.xml'

SNIPPETS = {
    'wscCode': (APP, [(339, 340)], {}),
    'wscWhen': (APP, [(341, 348)], {}),
    'edge': (ACT, [(50, 52)], {}),
    'screenInsets': (INS, [(37, 45)], {}),
    'insetsWhy': (INS, [(23, 26)], {}),
    'insetsConsumed': (INS, [(28, 30)], {}),
    'insetsTest': (INS, [(32, 34)], {}),
    'detailBp': (DET, [(172, 173)], {}),
    'detailIf': (DET, [(210, 210), (219, 223)], {}),
    'detailCap': (DET, [(331, 333)], {}),
    'cardCap': (TRI, [(888, 888)], {}),
    'grid': (SEA, [(189, 192)], {}),
    'legendBp': (PRO, [(196, 196), (208, 208)], {}),
    'legendWide': (PRO, [(311, 321)], {
        312: 'Row(modifier, …) {',
        313: 'GenreDonut(…)',
        314: 'GenreLegend(…, Modifier.weight(1f, fill = false).widthIn(max = WIDE_LEGEND_MAX_WIDTH))',
        317: 'Column(modifier.fillMaxWidth(), …) {',
        318: 'GenreDonut(…)',
        319: 'GenreLegend(…, Modifier.fillMaxWidth())',
    }),
    'menubar': (MAIN, [(234, 249)], {}),
    'accelerator': (MAIN, [(263, 265)], {}),
    'quitWhy': (MAIN, [(270, 272), (279, 279)], {}),
    'viewShortcuts': (MAIN, [(286, 289)], {}),
    'windowState': (WIN, [(32, 33), (35, 36)], {}),
    'triageKeys': (TRI, [(367, 385)], {}),
    'backOptIn': (MAN, [(25, 25)], {}),
}


def snippet(path, ranges, sub):
    lines = (ROOT / path).read_text().split('\n')
    out, indents = [], []
    for n, (a, b) in enumerate(ranges):
        chunk = []
        for i in range(a, b + 1):
            l = sub.get(i, lines[i - 1])
            if i in sub:
                l = ' ' * (len(lines[i - 1]) - len(lines[i - 1].lstrip())) + l
            chunk.append(l)
        if n:
            ind = len(chunk[0]) - len(chunk[0].lstrip())
            out.append(' ' * ind + '// …')
        out += chunk
    ind = min((len(l) - len(l.lstrip()) for l in out if l.strip()), default=0)
    ref = ', '.join(f'{a}-{b}' if a != b else str(a) for a, b in ranges)
    return [l[ind:] if l.strip() else '' for l in out], f"{path.split('/')[-1]}:{ref}"


commit = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
code, src = {}, {}
for k, (p, r, s) in SNIPPETS.items():
    code[k], src[k] = snippet(p, r, s)

body = [
    '// GENERATED by tools/gen-code.py from the Muviss sources. Do not edit by hand.',
    f'// Muviss commit {commit}.',
    '',
    f'export const MUVISS_COMMIT = {json.dumps(commit)};',
    '',
    '/** Lines of each snippet. `…` marks an explicit abbreviation or an elided range. */',
    'export const CODE = ' + json.dumps(code, ensure_ascii=False, indent=2) + ' as const;',
    '',
    '/** Where each snippet comes from: file:lines. */',
    'export const SRC = ' + json.dumps(src, ensure_ascii=False, indent=2) + ' as const;',
    '',
]
OUT.write_text('\n'.join(body))
print(f'wrote {OUT} ({len(code)} snippets, Muviss {commit})')
