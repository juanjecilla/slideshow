#!/usr/bin/env python3
"""Write docs/CONTENT-AUDIT.md (source slide -> scene.beat) from deck/slides.gen.ts. Usage: python3 -I tools/make_audit.py <deck_dir> <out.md>"""
import json
import sys

deck, out = sys.argv[1], sys.argv[2]
src = open(f'{deck}/slides.gen.ts', encoding='utf-8').read()
slides = json.loads(src.split('export const SLIDES: SlideData[] = ')[1].rsplit(';', 1)[0])
model = open(f'{deck}/model.ts', encoding='utf-8').read()
import re
ranges = [(int(a), int(b), t) for _, t, a, b in re.findall(r"id: '(\d+)', title: '([^']+)', from: (\d+), to: (\d+)", model)]
ranges = [(a, b, t) for a, b, t in [(int(x[2]), int(x[3]), x[1]) for x in re.findall(r"id: '(\d+)', title: '([^']+)', from: (\d+), to: (\d+)", model)]]

lines = [
    '# Content audit: Google Slides deck -> beats',
    '',
    'Source: "Dev Wars - El despertar del ego - Codemotion 2026" (Google Slides, 76 slides). Checked 2026-11-11.',
    'Generated by `tools/make_audit.py` from `deck/slides.gen.ts`; nothing in the deck was cut, reordered or added.',
    '',
    '| Slide | Scene.beat | Beats | Kept (text on the slide) | Media | Notes |',
    '|---|---|---|---|---|---|',
]
beat = {}
for si, (a, b, title) in enumerate(ranges, start=1):
    at = 1
    for s in slides:
        if not (a <= s['n'] <= b):
            continue
        n = (s['play'] + 1) if s.get('play') else s['steps'] + 1
        media = [i for i in s['items'] if i['kind'] in ('img', 'video')]
        vids = [i['video'] for i in media if i['kind'] == 'video']
        notes = []
        if s['steps']:
            notes.append(f"{s['steps']} click animation(s) -> beats {si}.{at + 1}-{si}.{at + s['steps']}")
        if s.get('play'):
            notes.append(f"beat {si}.{at + s['play']} starts the clips")
        text = (s['text'] or '(image only)').replace('|', '/')
        lines.append(f"| {s['n']} | {si}.{at}{'-' + str(si) + '.' + str(at + n - 1) if n > 1 else ''} | {n} | {text} | {len(media)} image(s){', clips: ' + ', '.join(vids) if vids else ''} | {'; '.join(notes)} |")
        at += n
lines += [
    '',
    '## Decisions taken on the speaker\'s behalf',
    '',
    '- Scenes follow the deck\'s own sections (8 scenes, see `deck/model.ts`); one slide = one beat, so the talk is the same 76 slides in the same order.',
    '- Click animations of the original (slides 2, 5, 25, 40) are one extra beat each; slide 25 has 12. No transitions existed in the original.',
    '- Slides 14 and 15 link their clips; here one extra beat plays them. The YouTube clip (`2Y3gmYO8TCE`) is bundled as a local file because the build forbids remote URLs.',
    '- Typos corrected: "¿Tiene senido?", "No exite", "Infraestructora", "Organizado GDG Aranjuez", "se vió" (the originals stay in the Google Slides).',
    '- Slide numbers (placeholder `sldNum`) are not drawn: the original slides do not show them.',
    '',
    '## Open questions',
    '',
    '- Event date: the landing says "Abr 2026" for Codemotion Madrid 2026; confirm the exact day.',
]
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('written', out, len(slides), 'slides')
